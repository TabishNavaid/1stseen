#!/usr/bin/env node
/**
 * Build the pictogram sprite: the larger, friendlier icons of the landing page and the first run (field chips,
 * program types, the three how-it-works steps, the celebration).
 *
 * The product's icons stay in the main sprite (scripts/build-icon-sprite.mjs). These are drawn by the same
 * `<use>` reference, so a pictogram costs one short element in the page and the sprite is fetched once.
 *
 * Writes apps/web/public/pictograms.svg and apps/web/components/ui/pictogram-names.ts. The sprite's content hash is
 * the `?v=` in every reference, so a changed sprite is never served from a stale cache.
 *
 * Usage: node apps/web/tools/build-pictograms.mjs          write both files
 *        node apps/web/tools/build-pictograms.mjs --check  exit 1 if either file is out of date
 */

import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import * as lucide from "lucide-react";

const WEB = resolve(import.meta.dirname, "..");
const SPRITE = resolve(WEB, "public/pictograms.svg");
const NAMES = resolve(WEB, "components/ui/pictogram-names.ts");

// By lucide-react export name. To add one: list it here, run this script, and commit both generated files.
const PICTOGRAMS = [
  "Backpack", "BellRing", "Binoculars", "Bot", "BrainCircuit", "CalendarSync", "ChartColumn", "ChartLine", "CodeXml", "Cpu",
  "GraduationCap", "Link2", "Palette", "PartyPopper", "Repeat", "Server", "Shield", "SquareKanban",
];

/** The sprite id for an export: "BrainCircuit" is "brain-circuit", "Link2" is "link-2". */
function kebab(exportName) {
  return exportName.replace(/([a-z0-9])([A-Z])/g, "$1-$2").replace(/([A-Za-z])(\d)/g, "$1-$2").toLowerCase();
}

function build() {
  const symbols = new Map();
  for (const exportName of PICTOGRAMS) {
    const component = lucide[exportName];
    if (!component) throw new Error(`lucide-react has no icon named ${exportName}`);
    const inner = renderToStaticMarkup(createElement(component)).replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "");
    if (!inner) throw new Error(`could not read ${exportName}'s markup`);
    symbols.set(kebab(exportName), `<symbol id="${kebab(exportName)}" viewBox="0 0 24 24">${inner}</symbol>`);
  }
  const names = [...symbols.keys()].sort();
  const sprite = `<svg xmlns="http://www.w3.org/2000/svg">${names.map((name) => symbols.get(name)).join("")}</svg>\n`;
  const version = createHash("sha256").update(sprite).digest("hex").slice(0, 10);
  const namesSource = [
    "// Generated by apps/web/tools/build-pictograms.mjs from the pictograms listed there. Do not edit.",
    "",
    `export const PICTOGRAM_SPRITE_VERSION = "${version}";`,
    "",
    "export const PICTOGRAM_NAMES = [",
    ...names.map((name) => `  "${name}",`),
    "] as const;",
    "",
    "export type PictogramName = (typeof PICTOGRAM_NAMES)[number];",
    "",
  ].join("\n");
  return { sprite, source: namesSource, count: names.length };
}

const { sprite, source, count } = build();
if (process.argv.includes("--check")) {
  const stale = [[SPRITE, sprite], [NAMES, source]].filter(([path, content]) => !existsSync(path) || readFileSync(path, "utf8") !== content);
  if (stale.length) {
    process.stderr.write(`Out of date: ${stale.map(([path]) => path).join(", ")}. Run node apps/web/tools/build-pictograms.mjs.\n`);
    process.exit(1);
  }
  process.stdout.write(`pictogram sprite up to date (${count} pictograms)\n`);
} else {
  writeFileSync(SPRITE, sprite);
  writeFileSync(NAMES, source);
  process.stdout.write(`wrote ${count} pictograms, ${Buffer.byteLength(sprite)} bytes\n`);
}
