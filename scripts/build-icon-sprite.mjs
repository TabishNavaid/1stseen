#!/usr/bin/env node
/**
 * Build the one icon sprite every surface references.
 *
 * Rendering lucide-react components inlined each icon's SVG paths into the page: 43.6 KiB of the dashboard's
 * 155.6 KiB of HTML. The product now draws icons with `<Icon name="…" />`, a `<use>` reference into
 * apps/web/public/icons.svg, which the browser fetches once and caches.
 *
 * Writes apps/web/public/icons.svg and apps/web/components/ui/icon-names.ts. The sprite's content hash is the
 * `?v=` in every reference, so a changed sprite is never served from a stale cache.
 *
 * Usage: node scripts/build-icon-sprite.mjs          write both files
 *        node scripts/build-icon-sprite.mjs --check  exit 1 if either file is out of date
 */

import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import * as lucide from "lucide-react";

const ROOT = resolve(import.meta.dirname, "..");
const SPRITE = resolve(ROOT, "apps/web/public/icons.svg");
const NAMES = resolve(ROOT, "apps/web/components/ui/icon-names.ts");

// The icons the product draws, by lucide-react export name. To add one: list it here, run this script, and
// commit both generated files. Use lucide's current names (LoaderCircle, not its alias Loader2).
const ICONS = [
  "Archive", "ArrowLeft", "ArrowRight", "ArrowUpRight", "Bell", "BellOff", "BellRing", "BriefcaseBusiness",
  "Building2", "CalendarClock", "CalendarDays", "CalendarPlus", "CalendarRange", "Check", "ChevronDown",
  "ChevronLeft", "ChevronRight", "ChevronUp", "CircleAlert", "CircleCheck", "CircleDashed", "CircleHelp",
  "CircleSlash", "Clock3", "Cpu", "Database", "Eye", "EyeOff", "FileSearch", "FileText", "Filter", "Gauge",
  "GitMerge", "History", "Info", "KeyRound", "List", "LoaderCircle", "LockKeyhole", "LogIn", "LogOut", "Mail",
  "MailCheck", "Menu", "MessageCircle", "Play", "Radar", "Radio", "RefreshCw", "RotateCw", "Search",
  "SearchCheck", "Send", "ShieldCheck", "Sparkles", "Target", "TrendingUp", "TriangleAlert", "UserPlus",
  "Waypoints", "X",
];

/** The sprite id for an export: "CalendarDays" is "calendar-days", "Clock3" is "clock-3". */
export function kebab(exportName) {
  return exportName.replace(/([a-z0-9])([A-Z])/g, "$1-$2").replace(/([A-Za-z])(\d)/g, "$1-$2").toLowerCase();
}

function build() {
  const symbols = new Map();
  for (const exportName of ICONS) {
    const component = lucide[exportName];
    if (!component) throw new Error(`lucide-react has no icon named ${exportName}`);
    const markup = renderToStaticMarkup(createElement(component));
    const name = kebab(exportName);
    const inner = markup.replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "");
    if (!name || !inner) throw new Error(`could not read ${exportName}'s markup`);
    symbols.set(name, `<symbol id="${name}" viewBox="0 0 24 24">${inner}</symbol>`);
  }
  const names = [...symbols.keys()].sort();
  // Stroke attributes live on the referencing <svg class="icon">, so one sprite serves every size and color.
  const sprite = `<svg xmlns="http://www.w3.org/2000/svg">${names.map((name) => symbols.get(name)).join("")}</svg>\n`;
  const version = createHash("sha256").update(sprite).digest("hex").slice(0, 10);
  const module = [
    "// Generated by scripts/build-icon-sprite.mjs from the icons listed there. Do not edit.",
    "",
    `export const ICON_SPRITE_VERSION = "${version}";`,
    "",
    "export const ICON_NAMES = [",
    ...names.map((name) => `  "${name}",`),
    "] as const;",
    "",
    "export type IconName = (typeof ICON_NAMES)[number];",
    "",
  ].join("\n");
  return { sprite, module, count: names.length };
}

const { sprite, module, count } = build();
if (process.argv.includes("--check")) {
  const stale = [[SPRITE, sprite], [NAMES, module]].filter(([path, content]) => !existsSync(path) || readFileSync(path, "utf8") !== content);
  if (stale.length) {
    process.stderr.write(`Out of date: ${stale.map(([path]) => path).join(", ")}. Run node scripts/build-icon-sprite.mjs.\n`);
    process.exit(1);
  }
  process.stdout.write(`icon sprite up to date (${count} icons)\n`);
} else {
  writeFileSync(SPRITE, sprite);
  writeFileSync(NAMES, module);
  process.stdout.write(`wrote ${count} icons, ${Buffer.byteLength(sprite)} bytes\n`);
}
